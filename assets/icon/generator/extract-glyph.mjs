// Pre-extract flattened glyph outlines from the app's EB Garamond into glyph.js.
// Usage: node extract-glyph.mjs   (needs `npm i opentype.js@1.3.4` somewhere resolvable)
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const require = createRequire(process.env.OPENTYPE_FROM || import.meta.url);
const opentype = require("opentype.js");
const here = new URL(".", import.meta.url).pathname;

function flatten(cmds, steps = 14) {
  const contours = []; let cur = null, px = 0, py = 0;
  for (const c of cmds) {
    if (c.type === "M") { cur = [[c.x, c.y]]; contours.push(cur); px = c.x; py = c.y; }
    else if (c.type === "L") { cur.push([c.x, c.y]); px = c.x; py = c.y; }
    else if (c.type === "Q") {
      for (let i = 1; i <= steps; i++) { const t = i / steps, u = 1 - t;
        cur.push([u*u*px + 2*u*t*c.x1 + t*t*c.x, u*u*py + 2*u*t*c.y1 + t*t*c.y]); }
      px = c.x; py = c.y;
    } else if (c.type === "C") {
      for (let i = 1; i <= steps; i++) { const t = i / steps, u = 1 - t;
        cur.push([u*u*u*px + 3*u*u*t*c.x1 + 3*u*t*t*c.x2 + t*t*t*c.x,
                  u*u*u*py + 3*u*u*t*c.y1 + 3*u*t*t*c.y2 + t*t*t*c.y]); }
      px = c.x; py = c.y;
    }
  }
  return contours.map(c => c.slice(0, -1).length ? c : c);
}

const out = {};
for (const [name, file] of [["regular", "EBGaramond-Regular.ttf"], ["medium", "EBGaramond-Medium.ttf"]]) {
  const font = opentype.loadSync(new URL("../../fonts/" + file, import.meta.url).pathname);
  for (const ch of ["a"]) {
    const p = font.getPath(ch, 0, 0, 1000); // y down, baseline at 0
    const contours = flatten(p.commands).map(c => c.map(([x, y]) => [+x.toFixed(2), +y.toFixed(2)]));
    out[name + ":" + ch] = contours;
  }
}
writeFileSync(here + "glyph.js", "// generated by extract-glyph.mjs — flattened EB Garamond outlines, 1000px em, y down, baseline y=0\nwindow.GLYPHS = " + JSON.stringify(out) + ";\n");
for (const k in out) console.log(k, out[k].length, "contours", out[k].map(c => c.length));
