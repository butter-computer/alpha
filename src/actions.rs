//! All actions and key bindings.

use gpui::{App, KeyBinding, actions};

actions!(
    alpha,
    [
        // app
        NewDoc,
        OpenDoc,
        Save,
        SaveAs,
        ExportMarkdown,
        ExportHtml,
        ToggleFind,
        TogglePalette,
        ToggleSettings,
        ToggleExportMenu,
        ToggleTheme,
        IncreaseFont,
        DecreaseFont,
        Quit,
        Cancel,
        // text editing
        Left,
        Right,
        Up,
        Down,
        WordLeft,
        WordRight,
        LineStart,
        LineEnd,
        DocStart,
        DocEnd,
        SelectLeft,
        SelectRight,
        SelectUp,
        SelectDown,
        SelectWordLeft,
        SelectWordRight,
        SelectLineStart,
        SelectLineEnd,
        SelectDocStart,
        SelectDocEnd,
        SelectAll,
        Backspace,
        Delete,
        DeleteWordLeft,
        DeleteToLineStart,
        Newline,
        Tab,
        Copy,
        Cut,
        Paste,
        Undo,
        Redo,
        // single-line inputs
        Confirm,
        ConfirmReverse,
    ]
);

pub fn bind_keys(cx: &mut App) {
    cx.bind_keys([
        // app
        KeyBinding::new("cmd-n", NewDoc, None),
        KeyBinding::new("cmd-o", OpenDoc, None),
        KeyBinding::new("cmd-s", Save, None),
        KeyBinding::new("cmd-shift-s", SaveAs, None),
        KeyBinding::new("cmd-f", ToggleFind, None),
        KeyBinding::new("cmd-k", TogglePalette, None),
        KeyBinding::new("cmd-,", ToggleSettings, None),
        KeyBinding::new("cmd-=", IncreaseFont, None),
        KeyBinding::new("cmd-+", IncreaseFont, None),
        KeyBinding::new("cmd--", DecreaseFont, None),
        KeyBinding::new("cmd-q", Quit, None),
        KeyBinding::new("escape", Cancel, None),
        // movement
        KeyBinding::new("left", Left, None),
        KeyBinding::new("right", Right, None),
        KeyBinding::new("up", Up, None),
        KeyBinding::new("down", Down, None),
        KeyBinding::new("alt-left", WordLeft, None),
        KeyBinding::new("alt-right", WordRight, None),
        KeyBinding::new("cmd-left", LineStart, None),
        KeyBinding::new("cmd-right", LineEnd, None),
        KeyBinding::new("home", LineStart, None),
        KeyBinding::new("end", LineEnd, None),
        KeyBinding::new("cmd-up", DocStart, None),
        KeyBinding::new("cmd-down", DocEnd, None),
        KeyBinding::new("ctrl-a", LineStart, None),
        KeyBinding::new("ctrl-e", LineEnd, None),
        // selection
        KeyBinding::new("shift-left", SelectLeft, None),
        KeyBinding::new("shift-right", SelectRight, None),
        KeyBinding::new("shift-up", SelectUp, None),
        KeyBinding::new("shift-down", SelectDown, None),
        KeyBinding::new("alt-shift-left", SelectWordLeft, None),
        KeyBinding::new("alt-shift-right", SelectWordRight, None),
        KeyBinding::new("cmd-shift-left", SelectLineStart, None),
        KeyBinding::new("cmd-shift-right", SelectLineEnd, None),
        KeyBinding::new("shift-home", SelectLineStart, None),
        KeyBinding::new("shift-end", SelectLineEnd, None),
        KeyBinding::new("cmd-shift-up", SelectDocStart, None),
        KeyBinding::new("cmd-shift-down", SelectDocEnd, None),
        KeyBinding::new("cmd-a", SelectAll, None),
        // editing
        KeyBinding::new("backspace", Backspace, None),
        KeyBinding::new("delete", Delete, None),
        KeyBinding::new("alt-backspace", DeleteWordLeft, None),
        KeyBinding::new("cmd-backspace", DeleteToLineStart, None),
        KeyBinding::new("enter", Newline, Some("Editor")),
        KeyBinding::new("tab", Tab, Some("Editor")),
        KeyBinding::new("cmd-c", Copy, None),
        KeyBinding::new("cmd-x", Cut, None),
        KeyBinding::new("cmd-v", Paste, None),
        KeyBinding::new("cmd-z", Undo, None),
        KeyBinding::new("cmd-shift-z", Redo, None),
        // single-line inputs
        KeyBinding::new("enter", Confirm, Some("LineInput")),
        KeyBinding::new("shift-enter", ConfirmReverse, Some("LineInput")),
    ]);
}
